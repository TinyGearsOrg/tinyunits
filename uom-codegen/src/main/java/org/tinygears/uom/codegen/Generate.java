package org.tinygears.uom.codegen;

import java.io.BufferedReader;
import java.io.IOException;
import java.io.PrintStream;
import java.io.Reader;
import java.io.UncheckedIOException;
import java.nio.charset.MalformedInputException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;
import java.util.stream.Stream;
import org.tinygears.uom.core.parse.DefinitionException;
import org.tinygears.uom.core.parse.DefinitionParser;
import org.tinygears.uom.core.parse.Definitions;

/** Generates the quantity sources from {@code data/}: {@code [--check] <dataDir> <outDir>}. */
public final class Generate {
    private static final String BASE_UNITS = "base.units";
    private static final String TYPES = "quantity-types.txt";
    // Must match SourceEmitter's header; only files starting with both lines count as stale.
    private static final String HEADER_1 = "// SPDX-License-Identifier: Apache-2.0";
    private static final String HEADER_2 = "// Generated by uom-codegen from data/quantity-types.txt; do not edit.";
    private static final String USAGE = "usage: Generate [--check] <dataDir> <outDir>";

    private Generate() {
    }

    public static void main(String[] args) {
        int status = run(args, System.err);
        if (status != 0) {
            System.exit(status);
        }
    }

    /** Returns 0 on success, 1 on a generation error or a {@code --check} difference, 2 on a usage error. */
    public static int run(String[] args, PrintStream err) {
        boolean check = args.length == 3 && args[0].equals("--check");
        if (!check && (args.length != 2 || args[0].startsWith("--"))) {
            err.println(USAGE);
            return 2;
        }
        Path dataDir = Path.of(args[check ? 1 : 0]);
        Path outDir = Path.of(args[check ? 2 : 1]);
        try {
            Map<String, String> files = generate(dataDir);
            if (check) {
                List<String> problems = differences(files, outDir);
                problems.forEach(err::println);
                return problems.isEmpty() ? 0 : 1;
            }
            write(files, outDir);
            return 0;
        } catch (GenerationException e) {
            err.println(e.getMessage());
            return 1;
        } catch (IOException | UncheckedIOException e) {
            err.println(outDir + ": " + e.getMessage());
            return 1;
        }
    }

    /** File name to source text for every generated file, sorted by name. */
    public static Map<String, String> generate(Path dataDir) {
        Definitions definitions;
        try (Reader in = open(dataDir, BASE_UNITS)) {
            definitions = DefinitionParser.parse(BASE_UNITS, in, name -> Files.newBufferedReader(
                    dataDir.resolve(name), StandardCharsets.UTF_8));
        } catch (DefinitionException e) {
            String prefix = e.source() + ":" + e.line() + ": ";
            throw new GenerationException(e.source(), e.line(), e.getMessage().substring(prefix.length()), e);
        } catch (IOException | UncheckedIOException e) {
            throw new GenerationException(BASE_UNITS, 0, "cannot read " + BASE_UNITS, e);
        }
        List<QuantityTypeSpec> specs;
        try (Reader in = open(dataDir, TYPES)) {
            specs = QuantityTypesParser.parse(TYPES, in, definitions);
        } catch (IOException | UncheckedIOException e) {
            throw new GenerationException(TYPES, 0, "cannot read " + TYPES, e);
        }
        if (specs.isEmpty()) {
            throw new GenerationException(TYPES, 0, "no quantity types defined");
        }
        Map<String, String> files = new TreeMap<>();
        for (QuantityTypeSpec s : specs) {
            files.put(s.name() + ".java", SourceEmitter.typedInterface(s));
            files.put(s.name() + "Double.java", SourceEmitter.doubleImplementation(s));
            files.put(s.name() + "Factory.java", SourceEmitter.factory(s, definitions));
        }
        files.put("QuantityTypes.java", SourceEmitter.registry(specs));
        return files;
    }

    private static Reader open(Path dataDir, String name) throws IOException {
        return Files.newBufferedReader(dataDir.resolve(name), StandardCharsets.UTF_8);
    }

    private static List<String> differences(Map<String, String> files, Path outDir) throws IOException {
        List<String> problems = new ArrayList<>();
        for (Map.Entry<String, String> f : files.entrySet()) {
            Path p = outDir.resolve(f.getKey());
            if (!Files.isRegularFile(p)) {
                problems.add("missing: " + f.getKey());
            } else if (!Files.readString(p, StandardCharsets.UTF_8).equals(f.getValue())) {
                problems.add("differs: " + f.getKey());
            }
        }
        for (Path p : stale(files, outDir)) {
            problems.add("stale: " + p.getFileName());
        }
        return problems;
    }

    private static void write(Map<String, String> files, Path outDir) throws IOException {
        Files.createDirectories(outDir);
        for (Map.Entry<String, String> f : files.entrySet()) {
            Files.write(outDir.resolve(f.getKey()), f.getValue().getBytes(StandardCharsets.UTF_8));
        }
        for (Path p : stale(files, outDir)) {
            Files.delete(p);
        }
    }

    /** Generated-looking {@code *.java} files in {@code outDir} that are no longer generated; others are kept. */
    private static List<Path> stale(Map<String, String> files, Path outDir) throws IOException {
        if (!Files.isDirectory(outDir)) {
            return List.of();
        }
        try (Stream<Path> s = Files.list(outDir)) {
            List<Path> result = new ArrayList<>();
            for (Path p : s.sorted().toList()) {
                String name = p.getFileName().toString();
                if (name.endsWith(".java") && !files.containsKey(name) && Files.isRegularFile(p)
                        && isGenerated(p)) {
                    result.add(p);
                }
            }
            return result;
        }
    }

    private static boolean isGenerated(Path p) throws IOException {
        try (BufferedReader in = Files.newBufferedReader(p, StandardCharsets.UTF_8)) {
            return HEADER_1.equals(in.readLine()) && HEADER_2.equals(in.readLine());
        } catch (MalformedInputException e) {
            return false;
        }
    }
}
