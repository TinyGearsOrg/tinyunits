package org.tinygears.uom.codegen;

import java.math.BigDecimal;
import java.math.BigInteger;
import java.util.HashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.stream.Collectors;

import org.tinygears.uom.core.Factor;
import org.tinygears.uom.core.parse.Definition;

/** Writes {@code docs/UNITS.md}: every unit of every catalog with its exact factor and offset to the system unit. */
public final class UnitTableEmitter {
    private static final String HEADER = "<!-- Generated by uom-codegen from data/*.units; do not edit. -->";

    private UnitTableEmitter() {
    }

    /** One section per catalog in map order, rows in the order of {@code Catalog.units()}. */
    public static String table(Map<String, CatalogBuilder.Catalog> catalogs, List<QuantityTypeSpec> types) {
        Map<String, CatalogEntry> byRef = new HashMap<>();
        catalogs.values().forEach(c -> c.entries().forEach(e -> byRef.put(c.className() + "." + e.constantName(), e)));
        Map<String, QuantityTypeSpec> byName = types.stream().collect(Collectors.toMap(QuantityTypeSpec::name, t -> t));
        StringBuilder out = new StringBuilder(HEADER).append("""


                # Catalog units

                Every unit of the generated catalogs in `org.tinygears.uom.systems`, one section per system. A value \
                in a unit is `factor * value + offset` in the system unit; factors and offsets are exact (`a|b` is a \
                fraction, `pi` is π). The quantity type `-` means the unit has none. Alternate units (`Hz`, `Bq`, \
                `rad`, `sr`, `Gy`, `Sv`) are their own system unit, so they show as `1 Gy` rather than `1 J/kg`.

                ## Systems

                | System | Data file | Symbols |
                |---|---|---|
                """);
        catalogs.values().forEach(
                c -> out.append("| [").append(c.className()).append("](#")
                        .append(c.className().toLowerCase(Locale.ROOT)).append(") | `data/").append(c.file())
                        .append("` | ").append(c.units().size()).append(" |\n"));
        for (CatalogBuilder.Catalog c : catalogs.values()) {
            out.append("\n## ").append(c.className())
                    .append("\n\n| Symbol | Name | Quantity type | Factor | Offset |\n|---|---|---|---|---|\n");
            for (String ref : c.units().values()) {
                CatalogEntry e = byRef.get(ref);
                Definition d = e.definition();
                QuantityTypeSpec spec = e.quantityType() == null ? null : byName.get(e.quantityType());
                String system = spec != null && spec.systemSymbol() != null
                        ? spec.systemSymbol()
                        : d.unit().getSystemUnit().getSymbol();
                Factor offset = d.unit().toSystemConverter().offset();
                out.append("| ").append(cell("`" + d.symbol() + "`")).append(" | ").append(cell(d.name())).append(" | ")
                        .append(e.quantityType() == null ? "-" : e.quantityType()).append(" | ")
                        .append(
                                cell(
                                        "`" + number(d.unit().toSystemConverter().factor())
                                                + (system.equals("1") ? "" : " " + system) + "`"))
                        .append(" | ").append(offset.isZero() ? "" : cell("`" + number(offset) + "`")).append(" |\n");
            }
        }
        return out.toString();
    }

    private static String cell(String text) {
        return text.replace("|", "\\|");
    }

    /** {@code n|d pi^k}; the rational part is a terminating decimal unless the fraction is shorter. */
    private static String number(Factor f) {
        BigInteger n = f.numerator();
        BigInteger d = f.denominator();
        String text = d.equals(BigInteger.ONE) ? n.toString() : n + "|" + d;
        try {
            BigDecimal value = new BigDecimal(n).divide(new BigDecimal(d));
            // below 1e-6 BigDecimal.toString switches to scientific notation, written like the data files (1e-7)
            String decimal = value.abs().compareTo(BigDecimal.ONE) < 0
                    ? value.stripTrailingZeros().toString().replace('E', 'e')
                    : value.toPlainString();
            text = decimal.length() <= text.length() ? decimal : text;
        } catch (ArithmeticException e) {
            // non-terminating: keep the fraction
        }
        int k = f.piExponent();
        if (k != 0) {
            text += k == 1 ? " pi" : " pi^" + k;
        }
        return f.rootIndex() == 1 ? text : "(" + text + ")^(1|" + f.rootIndex() + ")";
    }
}
