package org.tinygears.uom.codegen;

import java.util.ArrayList;
import java.util.List;
import java.util.Set;
import java.util.TreeSet;
import org.tinygears.uom.core.parse.Definition;
import org.tinygears.uom.core.parse.Definitions;

/** Writes the catalog class of typed unit constants and its system of units. */
public final class CatalogEmitter {
    private static final String UNIT = "org.tinygears.uom.core.UomUnit";
    private static final String INDENT = "                    ";

    private CatalogEmitter() {
    }

    /** The catalog class source; {@code definitions} is the parse of the catalog's file. */
    public static String catalog(CatalogBuilder.Catalog catalog, Definitions definitions) {
        String className = catalog.className();
        List<String> files = dataFiles(catalog.file(), definitions);
        StringBuilder out = new StringBuilder("""
                // SPDX-License-Identifier: Apache-2.0
                // Generated by uom-codegen from $H; do not edit.

                package org.tinygears.uom.systems;

                /** The $C units; generated from $J. */
                public final class $C {

                    private $C() {
                    }
                """.replace("$H", join(files.stream().map(f -> "data/" + f).toList()))
                .replace("$J", join(files.stream().map(f -> "{@code data/" + f + "}").toList()))
                .replace("$C", className));
        for (CatalogEntry e : catalog.entries()) {
            Definition d = e.definition();
            String type = e.quantityType() == null ? "?" : "javax.measure.quantity." + e.quantityType();
            String unit;
            try {
                unit = UnitExpressionEmitter.emitUnit(d.unit(), definitions);
            } catch (GenerationException x) {
                throw new GenerationException(d.source(), d.line(), x.getMessage(), x);
            }
            unit += ".named(" + UnitExpressionEmitter.literal(d.symbol()) + ", "
                    + UnitExpressionEmitter.literal(d.name()) + ")";
            out.append("\n    public static final ").append(UNIT).append('<').append(type).append("> ")
                    .append(e.constantName()).append(" =\n            ").append(UNIT).append(".unchecked(")
                    .append(wrap(unit)).append(");\n");
        }
        out.append("\n    public static final java.util.List<").append(UNIT).append("<?>> UNITS =\n")
                .append("            java.util.List.<").append(UNIT).append("<?>>of(")
                .append(args(catalog.units().values().stream().map(r -> local(r, className)).toList()))
                .append(";\n");
        out.append("\n    public static final java.util.Set<String> PREFIXABLE =\n            java.util.Set.of(")
                .append(args(catalog.prefixable().stream().sorted().map(UnitExpressionEmitter::literal).toList()))
                .append(";\n");
        List<String> pairs = new ArrayList<>();
        catalog.preferred().forEach((type, ref) -> pairs.add("java.util.Map.entry(javax.measure.quantity." + type
                + ".class, " + local(ref, className) + ")"));
        out.append("\n    public static final java.util.Map<Class<?>, ").append(UNIT).append("<?>> PREFERRED =\n")
                .append("            java.util.Map.<Class<?>, ").append(UNIT).append("<?>>ofEntries(")
                .append(args(pairs)).append(";\n");
        out.append("\n    public static final org.tinygears.uom.systems.UomSystemOfUnits SYSTEM =\n")
                .append("            new org.tinygears.uom.systems.UomSystemOfUnits(")
                .append(UnitExpressionEmitter.literal(className)).append(", UNITS, PREFERRED, PREFIXABLE);\n");
        return out.append("}\n").toString();
    }

    /** The catalog file, the other files its parse read (sorted), then the quantity types file. */
    static List<String> dataFiles(String file, Definitions definitions) {
        Set<String> read = new TreeSet<>();
        definitions.definitions().forEach(d -> read.add(d.source()));
        definitions.preferred().forEach(p -> read.add(p.source()));
        definitions.prefixed().forEach(p -> read.add(p.source()));
        read.remove(file);
        List<String> result = new ArrayList<>(List.of(file));
        result.addAll(read);
        result.add("quantity-types.txt");
        return result;
    }

    private static String join(List<String> items) {
        return String.join(", ", items.subList(0, items.size() - 1)) + " and " + items.get(items.size() - 1);
    }

    /** A reference to a constant of {@code className} is written unqualified. */
    private static String local(String ref, String className) {
        return ref.startsWith(className + ".") ? ref.substring(className.length() + 1) : ref;
    }

    /** A parenthesised argument list, one argument per line. */
    private static String args(List<String> items) {
        return items.isEmpty() ? ")" : "\n" + INDENT + String.join(",\n" + INDENT, items) + ")";
    }

    /** Puts each top-level method call of a unit expression on its own line. */
    private static String wrap(String expression) {
        StringBuilder out = new StringBuilder();
        int depth = 0;
        boolean quoted = false;
        for (int i = 0; i < expression.length(); i++) {
            char c = expression.charAt(i);
            if (quoted) {
                quoted = c != '"';
                if (c == '\\') {
                    out.append(c);
                    c = expression.charAt(++i);
                }
            } else if (c == '"') {
                quoted = true;
            } else if (c == '(') {
                depth++;
            } else if (c == ')') {
                depth--;
            } else if (c == '.' && depth == 0 && isCall(expression, i + 1)) {
                out.append('\n').append(INDENT);
            }
            out.append(c);
        }
        return out.toString();
    }

    private static boolean isCall(String s, int from) {
        int i = from;
        while (i < s.length() && Character.isJavaIdentifierPart(s.charAt(i))) {
            i++;
        }
        return i > from && Character.isLowerCase(s.charAt(from)) && i < s.length() && s.charAt(i) == '(';
    }
}
