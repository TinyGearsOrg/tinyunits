class SourceEmitterTest {
    private static final String PACKAGE = "org.tinygears.uom.quantity.";
    private static final List<QuantityTypeSpec> SPECS = QuantityTypesParser.parse("types.txt",
            new StringReader("Length m\nSpeed m / s => m/s:metre_per_second\n"), UnitExpressionEmitterTest.DEFS);
    private static final QuantityTypeSpec LENGTH = SPECS.get(0);
    private static final QuantityTypeSpec SPEED = SPECS.get(1);

    @TempDir
    Path tmp;

    /** Every emitted source for the two types, keyed by golden file name. */
    private static Map<String, String> sources() {
        Map<String, String> m = new LinkedHashMap<>();
        for (QuantityTypeSpec s : SPECS) {
            m.put(s.name(), SourceEmitter.typedInterface(s));
            m.put(s.name() + "Double", SourceEmitter.doubleImplementation(s));
            m.put(s.name() + "Decimal", SourceEmitter.decimalImplementation(s));
            m.put(s.name() + "Factory", SourceEmitter.factory(s, UnitExpressionEmitterTest.DEFS));
        }
        m.put("QuantityTypes", SourceEmitter.registry(SPECS));
        return m;
    }

    private static String golden(String name) throws Exception {
        try (InputStream in = SourceEmitterTest.class.getResourceAsStream("/golden/" + name + ".java")) {
            return new String(in.readAllBytes(), StandardCharsets.UTF_8);
        }
    }

    @ParameterizedTest
    @ValueSource(strings = {"Length", "LengthDouble", "LengthDecimal", "LengthFactory", "SpeedFactory", "QuantityTypes"})
    void matchesGolden(String name) throws Exception {
        assertEquals(golden(name), sources().get(name));
    }

    @Test
    void deterministicAndWellFormed() {
        Map<String, String> first = sources();
        assertEquals(first, sources());
        first.forEach((name, text) -> {
            assertFalse(text.contains("\r"), name);
            assertFalse(text.contains("\t"), name);
            assertTrue(text.endsWith("}\n"), name);
            assertEquals(List.of(), ImportCheck.problems(text, Set.of("Length", "Speed")), name);
            assertTrue(text.startsWith("""
                    // SPDX-License-Identifier: Apache-2.0
                    // Generated by uom-codegen from data/quantity-types.txt; do not edit.

                    package org.tinygears.uom.quantity;
                    """), name);
        });
    }

    @Test
    void baseUnitFactoryReusesTheConstant() {
        String factory = SourceEmitter.factory(LENGTH, UnitExpressionEmitterTest.DEFS);
        assertTrue(factory.contains("UomUnit.unchecked(BaseUnits.METRE);\n"), factory);
        assertFalse(factory.contains(".named("), factory);
        Definitions meter = DefinitionParser.parse("test.units", new StringReader("m:meter !L\n"), null);
        QuantityTypeSpec spec = QuantityTypesParser.parse("types.txt", new StringReader("Length m\n"), meter).get(0);
        assertTrue(SourceEmitter.factory(spec, meter)
                .contains("UomUnit.unchecked(BaseUnits.METRE.named(\"m\", \"meter\"));\n"));
    }

    @Test
    void decimalDeclarations() {
        String decimal = SourceEmitter.decimalImplementation(LENGTH);
        assertTrue(decimal.contains("""
                final class LengthDecimal
                        extends AbstractDecimalQuantity<javax.measure.quantity.Length, Length>
                        implements Length {
                """), decimal);
        assertTrue(decimal.contains("protected Length create(BigDecimal value,"), decimal);
        assertTrue(decimal.contains("return new LengthDecimal(value, unit, scale, mc);"), decimal);
        assertTrue(decimal.contains("protected Length createDouble(double value,"), decimal);
        assertTrue(decimal.contains("return new LengthDouble(value, unit, scale);"), decimal);
        assertTrue(SourceEmitter.doubleImplementation(LENGTH)
                .contains("return new LengthDecimal(value, unit, scale, mc);"));
        String hook = """
                    @Override
                    protected Class<javax.measure.quantity.Length> quantityType() {
                        return javax.measure.quantity.Length.class;
                    }
                """;
        assertTrue(decimal.contains(hook), decimal);
        assertTrue(SourceEmitter.doubleImplementation(LENGTH).contains(hook));
        String iface = SourceEmitter.typedInterface(LENGTH);
        for (String declaration : List.of("Length toDouble();", "Length toSystem(SystemOfUnits system);",
                "Length toDecimal(MathContext mc);",
                "static Length of(BigDecimal value, Unit<javax.measure.quantity.Length> unit) {",
                "static Length of(BigDecimal value, Unit<javax.measure.quantity.Length> unit,\n"
                        + "            Quantity.Scale scale) {",
                "static Length of(BigDecimal value, Unit<javax.measure.quantity.Length> unit,\n"
                        + "            Quantity.Scale scale, MathContext mc) {")) {
            assertTrue(iface.contains(declaration), declaration);
        }
        String factory = SourceEmitter.factory(LENGTH, UnitExpressionEmitterTest.DEFS);
        assertTrue(factory.contains("""
                        if (value instanceof BigDecimal d) {
                            return of(d, unit, scale);
                        }
                        if (value instanceof BigInteger i) {
                            return of(new BigDecimal(i), unit, scale);
                        }
                        return of(value.doubleValue(), unit, scale);
                """), factory);
    }

    // Each name is a generated type that clashes with a class the templates import; a stub stands in for its
    // standard type in javax.measure.quantity.
    @ParameterizedTest
    @ValueSource(strings = {"Unit", "Objects", "BigDecimal", "UomUnit"})
    void clashingTypeNameKeepsTheImportedClassQualified(String name) throws Exception {
        QuantityTypeSpec spec = new QuantityTypeSpec(name, "m", BaseUnits.METRE, null, null, "types.txt", 1, false);
        Map<String, String> byClass = new LinkedHashMap<>();
        byClass.put(PACKAGE + name, SourceEmitter.typedInterface(spec));
        byClass.put(PACKAGE + name + "Double", SourceEmitter.doubleImplementation(spec));
        byClass.put(PACKAGE + name + "Decimal", SourceEmitter.decimalImplementation(spec));
        byClass.put(PACKAGE + name + "Factory", SourceEmitter.factory(spec, UnitExpressionEmitterTest.DEFS));
        byClass.put(PACKAGE + "QuantityTypes", SourceEmitter.registry(List.of(spec)));
        String qualified = switch (name) {
            case "Unit" -> "javax.measure.Unit";
            case "Objects" -> "java.util.Objects";
            case "BigDecimal" -> "java.math.BigDecimal";
            default -> "org.tinygears.uom.core.UomUnit";
        };
        byClass.forEach((cls, text) -> {
            assertFalse(text.contains("import " + qualified + ";"), cls);
            assertEquals(List.of(), ImportCheck.problems(text, Set.of(name)), cls);
        });
        assertTrue(byClass.get(PACKAGE + name + "Factory").contains(qualified), qualified);
        byClass.put("javax.measure.quantity." + name, "package javax.measure.quantity;\n\npublic interface " + name
                + " extends javax.measure.Quantity<" + name + "> {\n}\n");
        InMemoryCompiler.compile(byClass, tmp).close();
    }

    @Test
    void factoryReportsSpecPosition() {
        UomUnit<?> x = UomUnit.of(Map.of(new UnitAtom("x", UomDimension.NONE), 1), Converters.IDENTITY, null, null);
        QuantityTypeSpec bad = new QuantityTypeSpec("Length", "x", x, null, null, "types.txt", 7, false);
        GenerationException e = assertThrows(GenerationException.class,
                () -> SourceEmitter.factory(bad, UnitExpressionEmitterTest.DEFS));
        assertEquals("types.txt:7: no definition for alternate unit 'x'", e.getMessage());
        assertEquals(7, e.line());
    }

    @Test
    void compilesAndRuns() throws Exception {
        Map<String, String> byClass = new LinkedHashMap<>();
        sources().forEach((name, text) -> byClass.put(PACKAGE + name, text));
        byClass.put(PACKAGE + "Speed", SourceEmitter.typedInterface(SPEED));
        byClass.put(PACKAGE + "SpeedDouble", SourceEmitter.doubleImplementation(SPEED));
        byClass.put(PACKAGE + "SpeedDecimal", SourceEmitter.decimalImplementation(SPEED));
        try (URLClassLoader loader = InMemoryCompiler.compile(byClass, tmp)) {
            Class<?> types = loader.loadClass(PACKAGE + "QuantityTypes");
            assertEquals(Set.of(javax.measure.quantity.Length.class, javax.measure.quantity.Speed.class),
                    types.getMethod("types").invoke(null));
            assertSame(BaseUnits.METRE, loader.loadClass(PACKAGE + "LengthFactory").getField("SYSTEM_UNIT").get(null));
            assertEquals(BaseUnits.METRE.divide(BaseUnits.SECOND),
                    loader.loadClass(PACKAGE + "SpeedFactory").getField("SYSTEM_UNIT").get(null));
            Object length = loader.loadClass(PACKAGE + "Length").getMethod("of", double.class, Unit.class)
                    .invoke(null, 1.5, BaseUnits.METRE);
            assertEquals(1.5, ((Quantity<?>) length).getValue());
            assertEquals(Quantity.Scale.ABSOLUTE, ((Quantity<?>) length).getScale());
            decimalsRun(loader);
        }
    }

    @SuppressWarnings("unchecked")
    private static void decimalsRun(ClassLoader loader) throws Exception {
        Class<?> iface = loader.loadClass(PACKAGE + "Length");
        Object d = iface.getMethod("of", BigDecimal.class, Unit.class)
                .invoke(null, new BigDecimal("1.50"), BaseUnits.METRE);
        assertEquals(PACKAGE + "LengthDecimal", d.getClass().getName());
        assertEquals(new BigDecimal("1.50"), ((Quantity<?>) d).getValue());
        assertEquals(MathContext.DECIMAL128, ((AbstractDecimalQuantity<?, ?>) d).mathContext());
        Object r = iface.getMethod("of", BigDecimal.class, Unit.class, Quantity.Scale.class, MathContext.class)
                .invoke(null, new BigDecimal("2"), BaseUnits.METRE, Quantity.Scale.RELATIVE, MathContext.DECIMAL32);
        assertEquals(Quantity.Scale.RELATIVE, ((Quantity<?>) r).getScale());
        assertEquals(MathContext.DECIMAL32, ((AbstractDecimalQuantity<?, ?>) r).mathContext());
        Object s = iface.getMethod("of", BigDecimal.class, Unit.class, Quantity.Scale.class)
                .invoke(null, new BigDecimal("3"), BaseUnits.METRE, Quantity.Scale.RELATIVE);
        assertEquals(MathContext.DECIMAL128, ((AbstractDecimalQuantity<?, ?>) s).mathContext());

        // to(system) on the typed interface keeps scale and context
        SystemOfUnits km = (SystemOfUnits) Proxy.newProxyInstance(SourceEmitterTest.class.getClassLoader(),
                new Class<?>[] {SystemOfUnits.class},
                (p, m, a) -> a != null && a[0] == javax.measure.quantity.Length.class
                        ? BaseUnits.METRE.multiply(1000) : null);
        java.lang.reflect.Method toSystem = iface.getMethod("toSystem", SystemOfUnits.class);
        assertEquals(iface, toSystem.getReturnType());
        Object inKm = toSystem.invoke(r, km);
        assertEquals(new BigDecimal("0.002"), ((Quantity<?>) inKm).getValue());
        assertEquals(Quantity.Scale.RELATIVE, ((Quantity<?>) inKm).getScale());
        assertEquals(MathContext.DECIMAL32, ((AbstractDecimalQuantity<?, ?>) inKm).mathContext());
        assertEquals(2e-3, ((Quantity<?>) toSystem.invoke(iface.getMethod("of", double.class, Unit.class)
                .invoke(null, 2.0, BaseUnits.METRE), km)).getValue());

        Object dbl = iface.getMethod("toDouble").invoke(d);
        assertTrue(iface.isInstance(dbl));
        assertEquals(1.5, ((Quantity<?>) dbl).getValue());
        Object back = iface.getMethod("toDecimal", MathContext.class).invoke(
                iface.getMethod("of", double.class, Unit.class).invoke(null, 1.25, BaseUnits.METRE), new MathContext(2));
        assertTrue(iface.isInstance(back));
        assertEquals(new BigDecimal("1.3"), ((Quantity<?>) back).getValue());
        assertEquals(new MathContext(2), ((AbstractDecimalQuantity<?, ?>) back).mathContext());
        // a double operand gives the double class of the typed interface
        Object mixed = ((Quantity<javax.measure.quantity.Length>) d).add(
                (Quantity<javax.measure.quantity.Length>) dbl);
        assertEquals(PACKAGE + "LengthDouble", mixed.getClass().getName());
        assertEquals(3.0, ((Quantity<?>) mixed).getValue());

        Object factory = loader.loadClass(PACKAGE + "LengthFactory").getField("INSTANCE").get(null);
        java.lang.reflect.Method create = factory.getClass().getMethod("create", Number.class, Unit.class);
        Quantity<?> fromDecimal = (Quantity<?>) create.invoke(factory, new BigDecimal("2.5"), BaseUnits.METRE);
        assertEquals(new BigDecimal("2.5"), fromDecimal.getValue());
        Quantity<?> fromInteger = (Quantity<?>) create.invoke(factory, BigInteger.TEN, BaseUnits.METRE);
        assertEquals(BigDecimal.TEN, fromInteger.getValue());
        assertEquals(MathContext.DECIMAL128, ((AbstractDecimalQuantity<?, ?>) fromInteger).mathContext());
        assertEquals(3.0, ((Quantity<?>) create.invoke(factory, 3, BaseUnits.METRE)).getValue());
        assertEquals(3.0, ((Quantity<?>) create.invoke(factory, 3L, BaseUnits.METRE)).getValue());
        java.lang.reflect.Method createScaled = factory.getClass()
                .getMethod("create", Number.class, Unit.class, Quantity.Scale.class);
        for (Number n : List.of(new BigDecimal("4"), BigInteger.TWO)) {
            Quantity<?> relative = (Quantity<?>) createScaled.invoke(factory, n, BaseUnits.METRE,
                    Quantity.Scale.RELATIVE);
            assertInstanceOf(BigDecimal.class, relative.getValue());
            assertEquals(Quantity.Scale.RELATIVE, relative.getScale());
        }

        Unit<?> foreign = (Unit<?>) Proxy.newProxyInstance(Unit.class.getClassLoader(), new Class<?>[] {Unit.class},
                (proxy, method, args) -> "foreign");
        java.lang.reflect.Method of = factory.getClass().getMethod("of", BigDecimal.class, Unit.class);
        InvocationTargetException e = assertThrows(InvocationTargetException.class,
                () -> of.invoke(factory, BigDecimal.ONE, foreign));
        assertInstanceOf(UnconvertibleException.class, e.getCause());
        e = assertThrows(InvocationTargetException.class, () -> of.invoke(factory, null, BaseUnits.METRE));
        assertInstanceOf(NullPointerException.class, e.getCause());
        e = assertThrows(InvocationTargetException.class, () -> of.invoke(factory, null, foreign));
        assertInstanceOf(NullPointerException.class, e.getCause());
        assertEquals("value", e.getCause().getMessage());
    }
}
