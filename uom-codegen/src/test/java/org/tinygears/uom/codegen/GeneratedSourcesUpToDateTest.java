package org.tinygears.uom.codegen;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.PrintStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;
import java.util.stream.Stream;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

class GeneratedSourcesUpToDateTest {
    private static final Path DATA = Path.of("../data");
    private static final Path QUANTITIES = Path.of("../uom-quantities/src/main/java/org/tinygears/uom/quantity");
    private static final Path SYSTEMS = Path.of("../uom-systems/src/main/java/org/tinygears/uom/systems");
    private static final String HEADER = """
            // SPDX-License-Identifier: Apache-2.0
            // Generated by uom-codegen from data/quantity-types.txt; do not edit.
            """;
    private static final String CATALOG_HEADER = """
            // SPDX-License-Identifier: Apache-2.0
            // Generated by uom-codegen from data/si.units and data/quantity-types.txt; do not edit.
            """;

    @TempDir
    Path tmp;

    private static Map<String, String> javaFiles(Path dir) throws IOException {
        Map<String, String> files = new TreeMap<>();
        if (Files.isDirectory(dir)) {
            try (Stream<Path> s = Files.list(dir)) {
                for (Path p : s.filter(p -> p.toString().endsWith(".java")).toList()) {
                    files.put(p.getFileName().toString(), Files.readString(p, StandardCharsets.UTF_8));
                }
            }
        }
        return files;
    }

    /** Problems between generated and committed files; only generated-looking files count as extra. */
    private static List<String> drift(Map<String, String> expected, Path dir) throws IOException {
        Map<String, String> actual = javaFiles(dir);
        List<String> problems = new ArrayList<>();
        expected.forEach((name, text) -> {
            if (!actual.containsKey(name)) {
                problems.add("missing: " + dir.resolve(name));
            } else if (!actual.get(name).equals(text)) {
                problems.add("differs: " + dir.resolve(name));
            }
        });
        actual.forEach((name, text) -> {
            if (!expected.containsKey(name) && text.startsWith("// SPDX-License-Identifier: Apache-2.0\n"
                    + "// Generated by uom-codegen")) {
                problems.add("extra: " + dir.resolve(name));
            }
        });
        return problems;
    }

    @Test
    void committedSourcesMatchTheGenerator() throws IOException {
        Generate.Output out = Generate.generate(DATA);
        List<String> problems = new ArrayList<>(drift(out.quantities(), QUANTITIES));
        problems.addAll(drift(out.systems(), SYSTEMS));
        assertTrue(problems.isEmpty(), () -> "Committed generated sources drift from data/; regenerate with"
                + " mvn -q -B -Pgenerate -pl uom-codegen -am process-classes\n" + String.join("\n", problems));
    }

    @Test
    void committedCatalogEqualsTheGeneratedText() throws IOException {
        assertEquals(Generate.generate(DATA).systems().get("SI.java"),
                Files.readString(SYSTEMS.resolve("SI.java"), StandardCharsets.UTF_8));
    }

    @Test
    void repositoryPinsLineEndings() throws IOException {
        Path attributes = Path.of("../.gitattributes");
        assertTrue(Files.isRegularFile(attributes), "missing " + attributes);
        assertTrue(Files.readAllLines(attributes).stream().anyMatch(l -> l.contains("eol=lf")),
                ".gitattributes must pin eol=lf");
    }

    @Test
    void generatorIsDeterministic() {
        assertEquals(Generate.generate(DATA), Generate.generate(DATA));
    }

    @Test
    void generatedFilesCarryTheHeader() {
        Generate.Output out = Generate.generate(DATA);
        assertEquals(100, out.quantities().size());
        out.quantities().forEach((name, text) -> assertTrue(text.startsWith(HEADER), name));
        assertEquals(Set.of("SI.java"), out.systems().keySet());
        assertTrue(out.systems().get("SI.java").startsWith(CATALOG_HEADER));
    }

    private Path dataDir(String types) throws IOException {
        Path dir = Files.createDirectories(tmp.resolve("data"));
        Files.copy(DATA.resolve("si.units"), dir.resolve("si.units"));
        if (types != null) {
            Files.writeString(dir.resolve("quantity-types.txt"), types);
        }
        return dir;
    }

    @Test
    void malformedTypesFileReportsFileAndLine() throws IOException {
        Path dir = dataDir("Length m\nFoo m\n");
        GenerationException e = assertThrows(GenerationException.class, () -> Generate.generate(dir));
        assertTrue(e.getMessage().startsWith("quantity-types.txt:2:"), e.getMessage());
    }

    @Test
    void emptyTypesFileIsRejected() throws IOException {
        Path dir = dataDir("# nothing\n");
        GenerationException e = assertThrows(GenerationException.class, () -> Generate.generate(dir));
        assertEquals("quantity-types.txt:0: no quantity types defined", e.getMessage());
    }

    @Test
    void missingDataFileIsReported() throws IOException {
        Path dir = dataDir(null);
        GenerationException e = assertThrows(GenerationException.class, () -> Generate.generate(dir));
        assertEquals("quantity-types.txt:0: cannot read quantity-types.txt", e.getMessage());
        e = assertThrows(GenerationException.class, () -> Generate.generate(tmp.resolve("nowhere")));
        assertEquals("si.units:0: cannot read si.units", e.getMessage());
    }

    @Test
    void definitionErrorsUseTheGeneratorFormat() throws IOException {
        Path dir = Files.createDirectories(tmp.resolve("bad"));
        Files.writeString(dir.resolve("si.units"), "m:metre !L\nx:foo bar\n");
        GenerationException e = assertThrows(GenerationException.class, () -> Generate.generate(dir));
        assertEquals("si.units:2: unknown unit 'bar'", e.getMessage());
    }

    private record Run(int status, String err) {
    }

    private static Run run(String... args) {
        ByteArrayOutputStream buf = new ByteArrayOutputStream();
        int status = Generate.run(args, new PrintStream(buf, true, StandardCharsets.UTF_8));
        return new Run(status, buf.toString(StandardCharsets.UTF_8));
    }

    private Run generateInto(Path q, Path sys) {
        return run(DATA.toString(), q.toString(), sys.toString());
    }

    private Run check(Path q, Path sys) {
        return run("--check", DATA.toString(), q.toString(), sys.toString());
    }

    @Test
    void checkModeReportsDifferencesInBothDirectories() throws IOException {
        Path q = tmp.resolve("q");
        Path sys = tmp.resolve("sys");
        assertEquals(0, generateInto(q, sys).status());
        assertEquals(0, check(q, sys).status());

        Files.writeString(q.resolve("Length.java"), "changed\n");
        Files.writeString(sys.resolve("SI.java"), "changed\n");
        Run r = check(q, sys);
        assertEquals(1, r.status());
        assertTrue(r.err().contains("differs: " + q.resolve("Length.java")), r.err());
        assertTrue(r.err().contains("differs: " + sys.resolve("SI.java")), r.err());

        Files.delete(q.resolve("Mass.java"));
        Files.delete(sys.resolve("SI.java"));
        Files.writeString(q.resolve("Old.java"), HEADER + "class Old {}\n");
        Files.writeString(sys.resolve("Old.java"), CATALOG_HEADER + "class Old {}\n");
        r = check(q, sys);
        assertEquals(1, r.status());
        assertTrue(r.err().contains("missing: " + q.resolve("Mass.java")), r.err());
        assertTrue(r.err().contains("missing: " + sys.resolve("SI.java")), r.err());
        assertTrue(r.err().contains("stale: " + q.resolve("Old.java")), r.err());
        assertTrue(r.err().contains("stale: " + sys.resolve("Old.java")), r.err());

        assertEquals(0, generateInto(q, sys).status());
        assertEquals(0, check(q, sys).status());
    }

    @Test
    void staleFilesAreOnlyDeletedWhenGenerated() throws IOException {
        Path q = Files.createDirectories(tmp.resolve("q"));
        Path sys = Files.createDirectories(tmp.resolve("sys"));
        String handWritten = "// SPDX-License-Identifier: Apache-2.0\n\nclass Keep {}\n";
        Files.writeString(q.resolve("Keep.java"), handWritten);
        Files.writeString(sys.resolve("Keep.java"), handWritten);
        Files.writeString(sys.resolve("Other.java"), "// SPDX-License-Identifier: Apache-2.0\n"
                + "// Generated by someone else\nclass Other {}\n");
        Files.writeString(q.resolve("Old.java"), HEADER + "class Old {}\n");
        Files.writeString(q.resolve("Older.java"), CATALOG_HEADER + "class Older {}\n");
        Files.writeString(sys.resolve("Old.java"), CATALOG_HEADER + "class Old {}\n");
        Files.writeString(sys.resolve("Older.java"), HEADER + "class Older {}\n");
        assertEquals(0, generateInto(q, sys).status());
        assertTrue(Files.exists(q.resolve("Keep.java")));
        assertTrue(Files.exists(sys.resolve("Keep.java")));
        assertTrue(Files.exists(sys.resolve("Other.java")));
        for (Path p : List.of(q.resolve("Old.java"), q.resolve("Older.java"), sys.resolve("Old.java"),
                sys.resolve("Older.java"))) {
            assertFalse(Files.exists(p), p.toString());
        }
        Generate.Output out = Generate.generate(DATA);
        assertEquals(out.quantities().get("Length.java"),
                Files.readString(q.resolve("Length.java"), StandardCharsets.UTF_8));
        assertEquals(out.systems().get("SI.java"), Files.readString(sys.resolve("SI.java"), StandardCharsets.UTF_8));
    }

    @Test
    void usageError() {
        Run r = run();
        assertEquals(2, r.status());
        assertTrue(r.err().startsWith("usage:"), r.err());
        assertEquals(2, run("data", "q").status());
        assertEquals(2, run("--check", "data", "q").status());
        assertEquals(2, run("--check", "data", "q", "s", "x").status());
        assertEquals(2, run("--force", "data", "q", "s").status());
    }

    @Test
    void generationErrorExitsWithOne() throws IOException {
        Run r = run(tmp.resolve("nowhere").toString(), tmp.resolve("q").toString(), tmp.resolve("s").toString());
        assertEquals(1, r.status());
        assertTrue(r.err().contains("si.units:0: cannot read si.units"), r.err());
    }
}
