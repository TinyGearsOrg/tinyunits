import org.junit.jupiter.api.Test;
import org.tinygears.uom.core.parse.DefinitionParser;
import org.tinygears.uom.core.parse.Definitions;

class UnitTableEmitterTest {
    private static final Map<String, String> SAMPLE = Map.of(
            "a.units", """
                    @system A
                    m:metre !L
                    s:second !T
                    K:kelvin !Θ
                    min:minute 60 s
                    °C:degree_Celsius K = x + 273.15
                    th:third_metre 1|3 m
                    pm:pi_metre pi|180 m
                    @prefixed m k
                    """,
            "b.units", """
                    @system B
                    @include a.units
                    @member m km
                    ft:foot 0.3048 m
                    """);

    private static String sample() {
        Map<String, Definitions> parsed = new LinkedHashMap<>();
        for (String f : List.of("a.units", "b.units")) {
            parsed.put(f, DefinitionParser.parse(f, new StringReader(SAMPLE.get(f)),
                    name -> new StringReader(SAMPLE.get(name))));
        }
        List<QuantityTypeSpec> types = QuantityTypesParser.parse("types.txt",
                new StringReader("Length m\nTemperature K\n"), parsed.get("a.units"));
        return UnitTableEmitter.table(CatalogBuilder.catalogs(parsed, types), types);
    }

    @Test
    void sampleTable() {
        assertEquals("""
                <!-- Generated by uom-codegen from data/*.units; do not edit. -->

                # Catalog units

                Every unit of the generated catalogs in `org.tinygears.uom.systems`, one section per system. A value \
                in a unit is `factor * value + offset` in the system unit; factors and offsets are exact (`a|b` is a \
                fraction, `pi` is π). The quantity type `-` means the unit has none. Alternate units (`Hz`, `Bq`, \
                `rad`, `sr`, `Gy`, `Sv`) are their own system unit, so they show as `1 Gy` rather than `1 J/kg`.

                ## Systems

                | System | Data file | Units |
                |---|---|---|
                | [A](#a) | `data/a.units` | 8 |
                | [B](#b) | `data/b.units` | 3 |

                ## A

                | Symbol | Name | Quantity type | Factor | Offset |
                |---|---|---|---|---|
                | `m` | metre | Length | `1 m` |  |
                | `s` | second | - | `1 s` |  |
                | `K` | kelvin | Temperature | `1 K` |  |
                | `min` | minute | - | `60 s` |  |
                | `°C` | degree Celsius | Temperature | `1 K` | `273.15` |
                | `th` | third metre | Length | `1\\|3 m` |  |
                | `pm` | pi metre | Length | `1\\|180 pi m` |  |
                | `km` | kilometre | Length | `1000 m` |  |

                ## B

                | Symbol | Name | Quantity type | Factor | Offset |
                |---|---|---|---|---|
                | `ft` | foot | Length | `0.3048 m` |  |
                | `m` | metre | Length | `1 m` |  |
                | `km` | kilometre | Length | `1000 m` |  |
                """, sample());
    }

    private static final String TABLE = Generate.generate(Path.of("../data")).docs().get("UNITS.md");

    private static List<String> section(String system) {
        String start = "\n## " + system + "\n";
        int from = TABLE.indexOf(start);
        int to = TABLE.indexOf("\n## ", from + start.length());
        String body = TABLE.substring(from + start.length(), to < 0 ? TABLE.length() : to);
        return body.lines().filter(l -> l.startsWith("| `")).toList();
    }

    private static String row(String system, String symbol) {
        return section(system).stream().filter(l -> l.startsWith("| `" + symbol + "` |")).findFirst().orElseThrow();
    }

    @Test
    void realSectionsFollowTheCatalogOrder() {
        List<String> headings = TABLE.lines().filter(l -> l.startsWith("## ") && !l.equals("## Systems")).toList();
        assertEquals(List.of("## SI", "## USCustomary", "## Imperial", "## CGS", "## ESU", "## EMU", "## Gaussian"),
                headings);
        assertTrue(TABLE.contains("| [ESU](#esu) | `data/cgs-esu.units` | 22 |\n"), TABLE);
    }

    // One row per symbol; Gaussian's Fr equals statC, so it has one row more than distinct units.
    @Test
    void realRowCountsPerSystem() {
        List<Integer> rows = new ArrayList<>();
        List<Integer> units = new ArrayList<>();
        for (String s : List.of("SI", "USCustomary", "Imperial", "CGS", "ESU", "EMU", "Gaussian")) {
            List<String> r = section(s);
            assertEquals(r.size(), r.stream().map(l -> l.substring(0, l.indexOf("` |"))).distinct().count(), s);
            rows.add(r.size());
            units.add((int) r.stream().map(l -> l.split(" \\| ", 4)[3]).distinct().count());
        }
        assertEquals(List.of(128, 35, 42, 16, 22, 29, 27), rows);
        assertEquals(List.of(128, 35, 42, 16, 22, 29, 26), units);
        assertEquals(row("ESU", "statC").replace("statC` | statcoulomb", "Fr` | franklin"), row("Gaussian", "Fr"));
    }

    @Test
    void realRowsMatchTheData() {
        assertEquals("| `ft` | foot | Length | `0.3048 m` |  |", row("USCustomary", "ft"));
        assertEquals("| `statC` | statcoulomb | ElectricCharge | `1\\|2997924580 C` |  |", row("ESU", "statC"));
        assertEquals("| `°C` | degree Celsius | Temperature | `1 K` | `273.15` |", row("SI", "°C"));
        assertEquals("| `°F` | degree Fahrenheit | Temperature | `5\\|9 K` | `45967\\|180` |",
                row("USCustomary", "°F"));
        assertEquals("| `eV` | electronvolt | Energy | `1.602176634e-19 J` |  |", row("SI", "eV"));
        assertEquals("| `keV` | kiloelectronvolt | Energy | `1.602176634e-16 J` |  |", row("SI", "keV"));
        assertEquals("| `GeV` | gigaelectronvolt | Energy | `1.602176634e-10 J` |  |", row("SI", "GeV"));
        assertEquals("| `Da` | dalton | Mass | `1.6605390666e-27 kg` |  |", row("SI", "Da"));
        // plain decimals down to 1e-6, as BigDecimal.toString
        assertEquals("| `cm³` | cubic centimetre | Volume | `0.000001 m³` |  |", row("CGS", "cm³"));
        assertEquals("| `erg` | erg | Energy | `1e-7 J` |  |", row("CGS", "erg"));
        assertEquals("| `deg` | degree | Angle | `1\\|180 pi rad` |  |", row("SI", "deg"));
        assertEquals("| `P` | poise | - | `0.1 kg/(m·s)` |  |", row("CGS", "P"));
        // members appear in every system that lists them
        assertEquals(row("SI", "cm"), row("CGS", "cm"));
        assertEquals(row("USCustomary", "ft"), row("Imperial", "ft"));
    }
}
